import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const root = process.cwd();
const sourceDir = join(root, 'apps', 'desktop', 'src', 'assets', 'engines');
const targetDir = join(root, 'apps', 'mobile', 'assets', 'engines');
const iconSource = readFileSync(join(root, 'apps', 'desktop', 'src', 'components', 'EngineIcon.tsx'), 'utf8');

const imports = [...iconSource.matchAll(/^import\s+(\w+)\s+from\s+'\.\.\/assets\/engines\/([\w.-]+)\.(svg|png)';$/gm)].map((match) => ({
  name: match[1],
  file: match[2],
  ext: match[3],
}));

const mapBody = iconSource.match(/const ENGINE_LOGOS[^=]*=\s*\{([\s\S]*?)\n\};/);
if (!mapBody) throw new Error('ENGINE_LOGOS map not found');
const entries = mapBody[1]
  .split('\n')
  .map((line) => line.trim().replace(/,$/, ''))
  .filter(Boolean)
  .map((line) => {
    const [engine, alias] = line.split(':').map((part) => part.trim());
    return { engine, name: alias ?? engine };
  });

const byName = new Map(imports.map((item) => [item.name, item]));
const mono = iconSource.match(/const MONO_ON_DARK = new Set<Engine>\(\[([\s\S]*?)\]\)/);
const bright = iconSource.match(/const BRIGHT_ON_LIGHT = new Set<Engine>\(\[([\s\S]*?)\]\)/);
const badges = iconSource.match(/const LETTER_BADGES[^=]*=\s*\{([\s\S]*?)\n\};/);
if (!mono || !bright || !badges) throw new Error('engine icon metadata not found');

mkdirSync(targetDir, { recursive: true });
for (const file of readdirSync(sourceDir)) {
  if (file.endsWith('.png')) copyFileSync(join(sourceDir, file), join(targetDir, basename(file)));
}

const pngImports = entries
  .map((entry) => byName.get(entry.name))
  .filter((item) => item?.ext === 'png')
  .map((item) => `import ${item.name} from '../assets/engines/${item.file}.png';`)
  .join('\n');

const svgEntries = entries
  .map((entry) => {
    const asset = byName.get(entry.name);
    if (!asset || asset.ext !== 'svg') return null;
    const raw = readFileSync(join(sourceDir, `${asset.file}.svg`), 'utf8').replace(/\s+/g, ' ').trim();
    return `  ${entry.engine}: \`${raw}\`,`;
  })
  .filter(Boolean)
  .join('\n');

const pngEntries = entries
  .map((entry) => {
    const asset = byName.get(entry.name);
    if (!asset || asset.ext !== 'png') return null;
    return `  ${entry.engine}: ${asset.name},`;
  })
  .filter(Boolean)
  .join('\n');

const engineList = (block) => block[1].split(',').map((item) => item.trim()).filter(Boolean);
const setBody = engineList(mono).join(', ');
const brightBody = engineList(bright).join(', ');
const badgeBody = badges[1].trim();

const output = `/* eslint-disable */
// Generated by scripts/sync-engine-logos.mjs from apps/desktop/src/assets/engines. Do not edit.
import type { Engine } from '@aidb/core';
${pngImports}

export const ENGINE_LOGO_SVG: Partial<Record<Engine, string>> = {
${svgEntries}
};

export const ENGINE_LOGO_PNG: Partial<Record<Engine, number>> = {
${pngEntries}
};

export const MONO_ENGINE_LOGOS = new Set<Engine>([${setBody}]);
export const BRIGHT_ENGINE_LOGOS = new Set<Engine>([${brightBody}]);
export const LETTER_BADGES: Partial<Record<Engine, { letter: string; color: string }>> = {
${badgeBody}
};
`;

writeFileSync(join(root, 'apps', 'mobile', 'src', 'engineLogos.ts'), output);
console.log(`engine logos synced: ${entries.length} engines, ${svgEntries ? (svgEntries.match(/`/g) ?? []).length / 2 : 0} svg, ${(pngEntries.match(/\n/g) ?? []).length} png`);
if (!existsSync(join(root, 'apps', 'mobile', 'src', 'images.d.ts'))) {
  writeFileSync(join(root, 'apps', 'mobile', 'src', 'images.d.ts'), "declare module '*.png' {\n  const source: number;\n  export default source;\n}\n");
}
