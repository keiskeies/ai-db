export function engineMeta(engine: Engine): EngineMeta {
  return ENGINES.find((item) => item.id === engine) ?? ENGINES[0];
}

export function engineDefaultPort(engine: Engine): number | undefined {
  return engineMeta(engine).defaultPort;
}

/** 该引擎能否在对象树中创建并删除集合/索引（驱动实现了对象生命周期）。 */
export function managesObjects(engine: Engine): boolean {
  return engineMeta(engine).capabilities.objectLifecycle === true;
}

/** 该引擎能否批量写入/删除文档或向量点。 */
export function writesDocuments(engine: Engine): boolean {
  return engineMeta(engine).capabilities.documentWrite === true;
}

/** 该引擎能否在对象信息面板里创建/删除索引。 */
export function managesIndexes(engine: Engine): boolean {
  return engineMeta(engine).capabilities.indexManage === true;
}

const ES_FIELD_TYPES = ['text', 'keyword', 'boolean', 'integer', 'long', 'float', 'double', 'date', 'ip', 'nested', 'object'];
const WEAVIATE_FIELD_TYPES = ['text', 'int', 'number', 'boolean', 'date'];

/** 该引擎能否给已有对象追加字段。 */
export function addField(engine: Engine): boolean {
  return engineMeta(engine).capabilities.fieldAdd === true;
}

/** 追加字段时可选的类型；不支持的引擎返回空数组。 */
export function fieldTypeOptions(engine: Engine): string[] {
  if (!addField(engine)) return [];
  return engineMeta(engine).transport === 'weaviate-http' ? [...WEAVIATE_FIELD_TYPES] : [...ES_FIELD_TYPES];
}

export function isEngine(value: unknown): value is Engine {
  return typeof value === 'string' && ENGINES.some((item) => item.id === value);
}

export const ENGINE_IDS: Engine[] = ENGINES.map((item) => item.id);

export function isSqlEngine(engine: Engine): boolean {
  return Boolean(engineMeta(engine).dialect);
}

/** 把产品引擎归一化为 SQL 方言；非 SQL 引擎调用会抛错，避免静默生成错误 SQL。 */
export function dialectOf(engine: Engine): DialectId {
  const dialect = engineMeta(engine).dialect;
  if (!dialect) throw new Error(`${engineMeta(engine).label} 不使用 SQL 方言`);
  return dialect;
}

export function engineUsesSchema(engine: Engine): boolean {
  const dialect = engineMeta(engine).dialect;
  return (
    dialect === 'postgres' ||
    dialect === 'mssql' ||
    dialect === 'oracle' ||
    dialect === 'clickhouse' ||
    dialect === 'dm' ||
    engine === 'cassandra' ||
    engine === 'scylla'
  );
}
