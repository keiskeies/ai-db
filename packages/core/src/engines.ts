import type { DataModel, DbObjectKind, DialectId, Engine, QueryLanguage, Transport } from './types';

export type EngineFamily = DialectId | 'mongodb' | 'redis' | 'graph' | 'vector' | 'search' | 'cassandra' | 'timeseries';

export interface EngineCapabilities {
  /** 对象树中该引擎支持的对象类型。 */
  objects: DbObjectKind[];
  ddl: boolean;
  explain: boolean;
  multiStatement: boolean;
  structureSync: boolean;
  dataCompare: boolean;
  backup: 'sql' | 'json' | 'none';
  gridEdit: boolean;
  users: boolean;
  /** 可在对象树里创建并删除集合/索引；只有实现了建删对象的驱动才置真。 */
  objectLifecycle?: boolean;
  /** 可批量写入与删除文档/向量点（驱动实现了 DocumentWriteDriver）。 */
  documentWrite?: boolean;
  /** 可在对象信息面板里创建/删除索引（驱动实现了 CollectionIndexDriver）。 */
  indexManage?: boolean;
  /** 可给已有对象追加字段（ES/OpenSearch 的 mapping、Weaviate 的 property）。 */
  fieldAdd?: boolean;
}

export interface EngineMeta {
  id: Engine;
  label: string;
  /** 方言家族；协议别名复用同一家族。 */
  family: EngineFamily;
  model: DataModel;
  /** 用哪个驱动实现。 */
  transport: Transport;
  /** SQL 方言；非 SQL 引擎为空。 */
  dialect?: DialectId;
  languages: QueryLanguage[];
  capabilities: EngineCapabilities;
  defaultPort?: number;
  defaultUsername?: string;
  /** 非关系型引擎的默认数据库/DB 索引。 */
  defaultDatabase?: string;
  fileBased: boolean;
  supportsSsh: boolean;
  supportsSsl: boolean;
  description: string;
  /** 已知限制或连接注意事项，UI 可展示。 */
  notes?: string;
  color: string;
}

function relational(overrides: Partial<EngineCapabilities> = {}): EngineCapabilities {
  return {
    objects: ['table', 'view'],
    ddl: true,
    explain: true,
    multiStatement: true,
    structureSync: true,
    dataCompare: true,
    backup: 'sql',
    gridEdit: true,
    users: true,
    ...overrides,
  };
}

