import test from 'node:test';
import assert from 'node:assert/strict';
import { buildCreateTable, buildInsert, buildSelectTable } from '../src/sql/ddl';

const cols = [
  { name: 'id', type: 'INTEGER', nullable: false, primaryKey: true, autoIncrement: true },
  { name: 'title', type: 'TEXT', nullable: false },
];

test('multi-engine create table dialects', () => {
  const mssql = buildCreateTable('sqlserver', { table: 'tasks', columns: cols, schema: 'dbo' });
  assert.match(mssql, /\[tasks\]/);
  assert.match(mssql, /IDENTITY\(1,1\)/);
  assert.match(mssql, /NVARCHAR\(MAX\)/);

  const oracle = buildCreateTable('oracle', { table: 'tasks', columns: cols, schema: 'SYSTEM' });
  assert.match(oracle, /"SYSTEM"."tasks"/);
  assert.match(oracle, /GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(oracle, /VARCHAR2\(4000\)/);

  const clickhouse = buildCreateTable('clickhouse', { table: 'tasks', columns: cols });
  assert.match(clickhouse, /ENGINE = MergeTree\(\)/);
  assert.match(clickhouse, /ORDER BY \(`id`\)/);
  assert.match(clickhouse, /`title` String NOT NULL/);

  const maria = buildCreateTable('mariadb', { table: 'tasks', columns: cols });
  assert.match(maria, /`id` INTEGER AUTO_INCREMENT/);
});

test('pagination dialects', () => {
  const mssql = buildSelectTable('sqlserver', 't', { limit: 10, offset: 5 });
  assert.match(mssql, /ORDER BY \(SELECT NULL\) OFFSET 5 ROWS FETCH NEXT 10 ROWS ONLY/);
  const oracle = buildSelectTable('oracle', 't', { limit: 10, offset: 5 });
  assert.match(oracle, /OFFSET 5 ROWS FETCH NEXT 10 ROWS ONLY/);
  const oracleFirst = buildSelectTable('oracle', 't', { limit: 10 });
  assert.match(oracleFirst, /FETCH FIRST 10 ROWS ONLY/);
  const clickhouse = buildSelectTable('clickhouse', 't', { limit: 10, offset: 5 });
  assert.match(clickhouse, /LIMIT 10 OFFSET 5/);
});

test('parameter placeholders per engine', () => {
  assert.match(buildInsert('oracle', 't', ['a', 'b'], 2), /:1, :2\), \(:3, :4/);
  assert.match(buildInsert('sqlserver', 't', ['a', 'b'], 2), /@p1, @p2\), \(@p3, @p4/);
  assert.match(buildInsert('cockroachdb', 't', ['a', 'b'], 2), /\$1, \$2\), \(\$3, \$4/);
  assert.match(buildInsert('clickhouse', 't', ['a', 'b'], 2), /\?, \?\), \(\?, \?\)/);
});
